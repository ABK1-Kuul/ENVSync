import { isValidVariableName } from "./validation.js";

/**
 * Text generation for `envsync init`. Output contains only variable names, fixed comments and
 * empty placeholders: no value from any file can reach generated content.
 */

export type GeneratedVariable = {
  name: string;
  /** Where the variable was first referenced; shown as a comment to help review. */
  firstReference?: { file: string; line: number };
};

export function renderConfig(variables: readonly GeneratedVariable[]): string {
  const lines = [
    "// EnvSync configuration: the contract for this project's environment variables.",
    "// EnvSync reads this file as data and never runs it, so keep every value literal.",
    '// Fields: required (default true), secret, external, type ("string" | "number" | "boolean" | "url"), description.',
    "// Generated by `envsync init` from static process.env references. Review each entry before committing.",
    "",
    "export default {",
  ];
  if (variables.length === 0) {
    lines.push("  variables: {},");
  } else {
    lines.push("  variables: {");
    for (const variable of variables) {
      assertValidName(variable.name);
      if (variable.firstReference) {
        lines.push(`    // First referenced at ${commentSafe(variable.firstReference.file)}:${variable.firstReference.line}`);
      }
      lines.push(`    ${variable.name}: { required: true },`);
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

export function renderEnvExample(names: readonly string[]): string {
  const lines = [
    "# Environment variables for this project. Copy to .env.local and fill in real values.",
    "# Generated by `envsync init`. Values are intentionally empty: never commit real secrets.",
    ...placeholders(names),
    "",
  ];
  return lines.join("\n");
}

/** Text to append to an existing `.env.example`, matching its line endings. */
export function renderEnvExampleAppend(existingText: string, names: readonly string[]): string {
  const eol = existingText.includes("\r\n") ? "\r\n" : "\n";
  const separator = existingText.length === 0 || /[\r\n]$/.test(existingText) ? "" : eol;
  return `${separator}${["# Added by `envsync init`", ...placeholders(names)].join(eol)}${eol}`;
}

function placeholders(names: readonly string[]): string[] {
  return names.map((name) => {
    assertValidName(name);
    return `${name}=`;
  });
}

function assertValidName(name: string): void {
  // Callers filter names first; this guards the generator itself against injection.
  if (!isValidVariableName(name)) throw new Error(`Refusing to generate an entry for an invalid variable name.`);
}

// Paths come from the filesystem; replace anything that could end the comment line or confuse a
// terminal. Numeric code points keep invisible characters out of this source file.
function commentSafe(text: string): string {
  return Array.from(text, (char) => (isUnsafeInComment(char.codePointAt(0) as number) ? "?" : char)).join("");
}

function isUnsafeInComment(code: number): boolean {
  return (
    code <= 0x1f ||
    (code >= 0x7f && code <= 0x9f) ||
    code === 0x200e ||
    code === 0x200f ||
    code === 0x2028 ||
    code === 0x2029 ||
    (code >= 0x202a && code <= 0x202e) ||
    (code >= 0x2066 && code <= 0x2069)
  );
}
